#!/usr/bin/env bash
#
# CDC-cache Quickstart — one command to deploy, seed, load, and verify.
#
# Current architecture (no Kafka, no UI):
#   Aurora MySQL (source)  ->  bulk loader / Debezium Server  ->  Valkey target (cache)
#
# This script stands up the minimal end-to-end test: it creates a small Aurora
# MySQL source and a small ElastiCache-for-Valkey target, seeds a sample
# workload, loads it into Valkey with transforms applied, and verifies the keys.
# The live-CDC path (Debezium Server on ECS) is a follow-on; this proves the
# tool end to end without it.
#
# PREREQUISITES
#   - Run from INSIDE the target VPC. ElastiCache has no public endpoint, so a
#     laptop can't reach it. Cheapest option: AWS CloudShell attached to your VPC
#     (free, no EC2). Any in-VPC host (EC2/Cloud9) or ephemeral Fargate task works.
#   - awscli v2 configured (or pass --profile), python3, and:
#       pip3 install pymysql valkey
#   - valkey-cli on PATH (optional, for the verify step).
#
# USAGE
#   ./quickstart.sh all                 # deploy + seed + load + verify (initial-load demo)
#   ./quickstart.sh deploy              # just create the infra (Aurora source + Valkey target)
#   ./quickstart.sh seed                # create schema + sample data
#   ./quickstart.sh load                # bulk-load into Valkey with transforms
#   ./quickstart.sh verify              # check keys landed in Valkey
#   ./quickstart.sh cdc                 # stand up the LIVE CDC pipeline (Debezium+broker+sink) + live transforms
#   ./quickstart.sh benchmark           # initial-load throughput (needs only source+target)
#   ./quickstart.sh benchmark-cdc       # end-to-end CDC throughput (needs the cdc pipeline running)
#   ./quickstart.sh teardown            # delete all stacks (cdc, broker, target, source)
#
# TYPICAL DEMO FLOW:
#   ./quickstart.sh all                 # Scenario 1: infra + initial load with transforms
#   ./quickstart.sh cdc                 # Scenario 2: live CDC — insert a row, watch it appear transformed
#
# CONFIG (env vars, all optional — sensible defaults):
#   AWS_PROFILE, AWS_REGION            AWS creds/region (AWS_REGION is required)
#   CDC_CACHE_DEBEZIUM_IMAGE, CDC_CACHE_SINK_IMAGE  your Debezium Server and Go sink image URIs (cdc)
#   CDC_CACHE_DB_MASTER_USERNAME       master user name for the deployed source (deploy); its password
#                                      is generated by RDS and kept in Secrets Manager
#   SOURCE_DB_SECRET_ARN               BYO mode: Secrets Manager secret (JSON username/password)
#   CDC_CACHE_PREFIX                        stack/name prefix (default: cdc-cache-demo)
#   CDC_CACHE_VPC_ID, CDC_CACHE_SUBNET_IDS       override VPC/subnets (default: auto-detect default VPC)
#   CDC_CACHE_USERS/CDC_CACHE_MERCHANTS/CDC_CACHE_PRODUCTS   seed row counts (default 1000/200/500)
#   CDC_CACHE_TABLES, CDC_CACHE_TRANSFORMS       override which tables to load / the transform spec (load)
#   CDC_CACHE_CDC_TABLE, CDC_CACHE_CDC_TRANSFORMS  override the live-CDC table / its transform spec (cdc)
#
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
EXAMPLE_DIR="$SCRIPT_DIR/examples/my-pipeline"
# Which transform spec to apply. Override with CDC_CACHE_TRANSFORMS=/path/to/transforms.json
# The spec is keyed by table name; each table's filter/computed/columns/rename is
# applied automatically during load. Change the file to change what gets cached/how.
TRANSFORMS="${CDC_CACHE_TRANSFORMS:-$EXAMPLE_DIR/setup/transforms.json}"
LOADER_DIR="$SCRIPT_DIR/data-plane/bulk-loader"

REGION="${AWS_REGION:?set AWS_REGION}"
PREFIX="${CDC_CACHE_PREFIX:-cdc-cache-demo}"
SRC_STACK="${PREFIX}-source"
TGT_STACK="${PREFIX}-target"
BROKER_STACK="${PREFIX}-broker"
CDC_STACK="${PREFIX}-cdc"
ECS_CLUSTER="${PREFIX}-cluster"
DB_NAME="Inventory"

# Live-CDC demo table + its transform spec (applied by the sink on the CDC path).
# Default: products (filter status=active + computed price_cents). Override the
# table with CDC_CACHE_CDC_TABLE and the spec with CDC_CACHE_CDC_TRANSFORMS.
CDC_TABLE="${CDC_CACHE_CDC_TABLE:-products}"
if [ -n "${CDC_CACHE_CDC_TRANSFORMS:-}" ]; then
  CDC_TRANSFORMS_JSON="$CDC_CACHE_CDC_TRANSFORMS"
else
  CDC_TRANSFORMS_JSON='{"tables":{"products":{"filter":{"field":"status","op":"=","value":"active"},"computed":[{"name":"price_cents","expr":"price*100"}]}}}'
fi
AWS=(aws --region "$REGION")
[ -n "${AWS_PROFILE:-}" ] && AWS+=(--profile "$AWS_PROFILE")

# Tables to load: "table:pk" pairs (matches setup/schema.sql + transforms).
# Override with CDC_CACHE_TABLES (space- or comma-separated), e.g.
#   CDC_CACHE_TABLES="products:id merchants:merchant_id" ./quickstart.sh load
if [ -n "${CDC_CACHE_TABLES:-}" ]; then
  IFS=', ' read -r -a TABLES <<< "$CDC_CACHE_TABLES"
else
  TABLES=("products:id" "merchants:merchant_id" "users:id" "customer_kyc:customer_id" "customer_txn_aggregates:customer_id")
fi

# Benchmark defaults (override via env). Small by default so a demo is quick/cheap;
# raise CDC_CACHE_BENCH_SIZES to reproduce the doc numbers (e.g. 1000000,2000000,5000000).
BENCH_SIZES="${CDC_CACHE_BENCH_SIZES:-100000,500000}"
BENCH_WORKERS="${CDC_CACHE_BENCH_WORKERS:-16}"
BENCH_CDC_N="${CDC_CACHE_BENCH_CDC_N:-200000}"
BENCH_CDC_BATCH="${CDC_CACHE_BENCH_CDC_BATCH:-1000}"
LOADER_BENCH_DIR="$SCRIPT_DIR/data-plane/bulk-loader"

c_ok()   { printf "\033[32m[OK]\033[0m %s\n" "$*"; }
c_step() { printf "\n\033[36m==>\033[0m %s\n" "$*"; }
c_err()  { printf "\033[31m[ERROR]\033[0m %s\n" "$*" >&2; }
die()    { c_err "$*"; exit 1; }

trap 'c_err "Step failed (line $LINENO). Check: '"$0"' status  |  CloudFormation console  |  aws cloudformation describe-stack-events"' ERR

# ─────────────────────────────────────────────────────────────────────────────
preflight() {
  c_step "Preflight checks"
  command -v aws  >/dev/null || die "awscli not found"
  command -v python3 >/dev/null || die "python3 not found"
  "${AWS[@]}" sts get-caller-identity >/dev/null || die "AWS credentials not valid (try: aws sso login / mwinit)"
  python3 -c "import pymysql, valkey" 2>/dev/null || die "python deps missing: pip3 install pymysql valkey"
  [ -f "$TRANSFORMS" ] || die "transforms not found at $TRANSFORMS"
  c_ok "tooling + credentials present (region=$REGION)"
}

detect_network() {
  if [ -n "${CDC_CACHE_VPC_ID:-}" ] && [ -n "${CDC_CACHE_SUBNET_IDS:-}" ]; then
    VPC_ID="$CDC_CACHE_VPC_ID"; SUBNETS="$CDC_CACHE_SUBNET_IDS"
  else
    c_step "Auto-detecting default VPC + subnets"
    VPC_ID="$("${AWS[@]}" ec2 describe-vpcs --filters Name=isDefault,Values=true \
      --query 'Vpcs[0].VpcId' --output text)"
    [ "$VPC_ID" != "None" ] || die "no default VPC; set CDC_CACHE_VPC_ID and CDC_CACHE_SUBNET_IDS"
    SUBNETS="$("${AWS[@]}" ec2 describe-subnets --filters Name=vpc-id,Values="$VPC_ID" \
      --query 'Subnets[].SubnetId' --output text | tr '\t' ',')"
  fi
  VPC_CIDR="$("${AWS[@]}" ec2 describe-vpcs --vpc-ids "$VPC_ID" \
    --query 'Vpcs[0].CidrBlock' --output text)"
  c_ok "VPC=$VPC_ID  CIDR=$VPC_CIDR  subnets=${SUBNETS}"
}

deploy_stack() {  # name template "Param=Val ..."
  local name="$1" tpl="$2"; shift 2
  c_step "Deploying $name  ($tpl)"
  "${AWS[@]}" cloudformation deploy \
    --stack-name "$name" \
    --template-file "$SCRIPT_DIR/infra/$tpl" \
    --capabilities CAPABILITY_NAMED_IAM CAPABILITY_IAM \
    --no-fail-on-empty-changeset \
    --parameter-overrides "$@"
  c_ok "$name deployed"
}

stack_output() {  # stack key
  "${AWS[@]}" cloudformation describe-stacks --stack-name "$1" \
    --query "Stacks[0].Outputs[?OutputKey=='$2'].OutputValue" --output text
}

# ─────────────────────────────────────────────────────────────────────────────
do_deploy() {
  detect_network
  # Small/cheap footprint for a demo: single shard, smallest nodes, min ACUs.
  deploy_stack "$SRC_STACK" "aurora-serverless-mysql.yaml" \
    "VpcId=$VPC_ID" "SubnetIds=$SUBNETS" "DBName=$DB_NAME" \
    "MasterUsername=${CDC_CACHE_DB_MASTER_USERNAME:?set CDC_CACHE_DB_MASTER_USERNAME}" \
    "MinCapacity=0.5" "MaxCapacity=2" "ClientCidr=$VPC_CIDR"
  deploy_stack "$TGT_STACK" "valkey-cluster-with-monitoring.yaml" \
    "ClusterName=${PREFIX}-valkey" "VpcId=$VPC_ID" "SubnetIds=$SUBNETS" \
    "NodeType=cache.t3.small" "NumShards=1" "ReplicasPerShard=1" \
    "AllowedCIDR=$VPC_CIDR"
  c_ok "Infra ready. Next: $0 seed"
}

# Read the DB user and password from a Secrets Manager secret (JSON with
# username and password) into this process's environment, for the loaders only.
read_db_secret() {  # secret-arn
  local secret_json; secret_json="$("${AWS[@]}" secretsmanager get-secret-value \
    --secret-id "$1" --query SecretString --output text)" \
    || die "could not read the DB secret ($1)"
  export SOURCE_DB_USER; SOURCE_DB_USER="$(echo "$secret_json" | python3 -c 'import sys,json;print(json.load(sys.stdin)["username"])')"
  export SOURCE_DB_PASSWORD; SOURCE_DB_PASSWORD="$(echo "$secret_json" | python3 -c 'import sys,json;print(json.load(sys.stdin)["password"])')"
}

load_env() {
  # BYO mode: if you already exported your own endpoints, use them as-is and
  # skip the stack lookup. Credentials always come from a Secrets Manager secret
  # (JSON with username and password): SOURCE_DB_SECRET_ARN in BYO mode.
  if [ -n "${SOURCE_DB_HOST:-}" ] && [ -n "${VALKEY_HOST:-}" ]; then
    [ -n "${SOURCE_DB_SECRET_ARN:-}" ] || die "BYO mode: set SOURCE_DB_SECRET_ARN (or unset SOURCE_DB_HOST/VALKEY_HOST to use the deployed stacks)"
    export SOURCE_DB_PORT="${SOURCE_DB_PORT:-3306}" \
           SOURCE_DB_NAME="${SOURCE_DB_NAME:-$DB_NAME}" VALKEY_PORT="${VALKEY_PORT:-6379}" \
           VALKEY_SSL="${VALKEY_SSL:-true}"
    read_db_secret "$SOURCE_DB_SECRET_ARN"
    c_ok "Using caller-provided endpoints (BYO mode)"
    return
  fi

  # Deployed-stack mode: read endpoints from the CloudFormation outputs.
  SOURCE_DB_HOST="$(stack_output "$SRC_STACK" ClusterEndpoint)"
  [ -n "$SOURCE_DB_HOST" ] && [ "$SOURCE_DB_HOST" != "None" ] || die "source stack not deployed yet (run: $0 deploy), or export SOURCE_DB_HOST/SOURCE_DB_SECRET_ARN for BYO"
  export SOURCE_DB_HOST
  export SOURCE_DB_PORT=3306
  export SOURCE_DB_NAME="$DB_NAME"

  # Credentials: the RDS-managed secret that aurora-serverless-*.yaml created
  # (ManageMasterUserPassword).
  SOURCE_DB_SECRET_ARN="$(stack_output "$SRC_STACK" MasterUserSecretArn)"
  [ -n "$SOURCE_DB_SECRET_ARN" ] && [ "$SOURCE_DB_SECRET_ARN" != "None" ] \
    || die "the source stack has no MasterUserSecretArn — export SOURCE_DB_SECRET_ARN (BYO mode)"
  export SOURCE_DB_SECRET_ARN
  read_db_secret "$SOURCE_DB_SECRET_ARN"

  export VALKEY_HOST; VALKEY_HOST="$(stack_output "$TGT_STACK" ClusterEndpoint)"
  export VALKEY_PORT; VALKEY_PORT="$(stack_output "$TGT_STACK" ClusterPort)"
  export VALKEY_SSL=true
  [ -n "$VALKEY_HOST" ] && [ "$VALKEY_HOST" != "None" ] || die "target stack not deployed yet (run: $0 deploy), or export VALKEY_HOST for BYO"
}

do_seed() {
  load_env
  c_step "Seeding sample workload into $SOURCE_DB_HOST"
  python3 "$EXAMPLE_DIR/setup/seed.py" \
    --users "${CDC_CACHE_USERS:-1000}" --merchants "${CDC_CACHE_MERCHANTS:-200}" --products "${CDC_CACHE_PRODUCTS:-500}"
  c_ok "Seed complete"
}

do_load() {
  load_env
  c_step "Bulk-loading tables into Valkey (transforms applied)"
  ( cd "$LOADER_DIR"
    for entry in "${TABLES[@]}"; do
      local t="${entry%%:*}" pk="${entry##*:}"
      echo "  -> $t (pk=$pk)"
      python3 bulk_loader.py --source mysql --table "$t" --pk "$pk" --transforms "$TRANSFORMS"
    done
  )
  c_ok "Load complete"
}

do_verify() {
  load_env
  c_step "Verifying keys in Valkey ($VALKEY_HOST:$VALKEY_PORT)"
  if command -v valkey-cli >/dev/null; then
    for t in products merchants users customer_kyc; do
      printf "  %-24s " "$t:1"
      valkey-cli -h "$VALKEY_HOST" -p "$VALKEY_PORT" --tls -c HGETALL "$t:1" | head -8 | tr '\n' ' '; echo
    done
  else
    python3 - <<PY
import os
from valkey.cluster import ValkeyCluster
r = ValkeyCluster(host=os.environ["VALKEY_HOST"], port=int(os.environ["VALKEY_PORT"]),
                  ssl=True, ssl_cert_reqs=None, decode_responses=True)
for t in ("products","merchants","users","customer_kyc"):
    print(f"  {t}:1 ->", dict(list(r.hgetall(f"{t}:1").items())[:6]) or "(empty/miss)")
PY
  fi
  c_ok "Verify done. products:* should exist only for active products and include price_cents;"
  c_ok "merchants:* should have 'tier' (renamed from risk_tier) and no timestamps."
}

do_cdc() {
  # Stand up the LIVE CDC pipeline (Debezium -> broker Valkey Streams -> Go sink)
  # on top of the source + target created by `deploy`. Reuses the existing ECR
  # images. Demonstrates live transforms (Scenario 2): insert a row in Aurora and
  # watch it appear in the target cache, transformed.
  detect_network
  load_env   # SOURCE_DB_HOST, SOURCE_DB_SECRET_ARN, VALKEY_HOST/PORT (from deployed stacks)

  local aurora_sg tgt_sg
  aurora_sg="$(stack_output "$SRC_STACK" SecurityGroupId)"
  tgt_sg="$(stack_output "$TGT_STACK" SecurityGroupId)"
  [ -n "$aurora_sg" ] && [ "$aurora_sg" != "None" ] || die "source SecurityGroupId not found — run: $0 deploy"
  [ -n "$tgt_sg" ]    && [ "$tgt_sg" != "None" ]    || die "target SecurityGroupId not found — run: $0 deploy"

  # The CDC task reads the user and password straight from the DB secret
  # (ECS secrets, valueFrom); no copy of the password is made.

  c_step "Ensuring ECS cluster ($ECS_CLUSTER)"
  "${AWS[@]}" ecs create-cluster --cluster-name "$ECS_CLUSTER" >/dev/null
  c_ok "ECS cluster ready"

  # Broker (cluster-mode-disabled Valkey Streams buffer)
  deploy_stack "$BROKER_STACK" "broker-quickstart.yaml" \
    "ClusterName=${PREFIX}-broker-cache" "VpcId=$VPC_ID" "SubnetIds=$SUBNETS" "AllowedCIDR=$VPC_CIDR"
  local broker_host broker_sg
  broker_host="$(stack_output "$BROKER_STACK" PrimaryEndpoint)"
  broker_sg="$(stack_output "$BROKER_STACK" SecurityGroupId)"
  [ -n "$broker_host" ] && [ "$broker_host" != "None" ] || die "broker endpoint not found after deploy"

  # CDC pipeline: Debezium + Go sink on Fargate, wired to source/broker/target.
  deploy_stack "$CDC_STACK" "cdc-ecs.yaml" \
    "ClusterName=$ECS_CLUSTER" "VpcId=$VPC_ID" "SubnetIds=$SUBNETS" \
    "BrokerHost=$broker_host" "BrokerPort=6379" "BrokerSSL=false" "BrokerSecurityGroupId=$broker_sg" \
    "TargetHost=$VALKEY_HOST" "TargetPort=$VALKEY_PORT" "TargetSSL=true" "TargetCluster=true" "TargetSecurityGroupId=$tgt_sg" \
    "SourceDBHost=$SOURCE_DB_HOST" "SourceDBPort=3306" "SourceDBName=$DB_NAME" \
    "DBSecretArn=$SOURCE_DB_SECRET_ARN" "AuroraSecurityGroupId=$aurora_sg" \
    "Tables=Inventory.${CDC_TABLE}" "TopicPrefix=cdc-cache" "SnapshotMode=schema_only" \
    "StreamKey=data:cdc-cache.Inventory.${CDC_TABLE}" "StreamTable=${CDC_TABLE}" \
    "TransformsJson=${CDC_TRANSFORMS_JSON}" \
    "DebeziumImage=${CDC_CACHE_DEBEZIUM_IMAGE:?set CDC_CACHE_DEBEZIUM_IMAGE}" \
    "SinkImage=${CDC_CACHE_SINK_IMAGE:?set CDC_CACHE_SINK_IMAGE}"

  c_ok "Live CDC pipeline deployed (Debezium + broker + sink)."
  c_step "Try it (Scenario 2 — live transform):"
  cat <<EOF
  # Debezium takes ~1-2 min to start streaming. Then insert an ACTIVE product:
  mysql -h $SOURCE_DB_HOST -u <username from the DB secret> -p $DB_NAME \\
    -e "INSERT INTO products (sku,name,category,price,status) VALUES ('DEMO-1','Live Widget','demo',19.99,'active');"
  sleep 3
  valkey-cli -h $VALKEY_HOST -p $VALKEY_PORT --tls -c HGETALL products:<new_id>   # -> price_cents=1999

  # Insert an INACTIVE product -> filtered out, never cached:
  mysql -h $SOURCE_DB_HOST -u <username from the DB secret> -p $DB_NAME \\
    -e "INSERT INTO products (sku,name,category,price,status) VALUES ('DEMO-2','Hidden','demo',9.99,'inactive');"

  # Pipeline health: ECS services ${CDC_STACK}-debezium / ${CDC_STACK}-sink;
  # logs in CloudWatch /ecs/${CDC_STACK}/debezium and /ecs/${CDC_STACK}/sink.
EOF
}

do_teardown() {
  c_step "Deleting stacks ($CDC_STACK, $BROKER_STACK, $TGT_STACK, $SRC_STACK)"
  "${AWS[@]}" cloudformation delete-stack --stack-name "$CDC_STACK" || true
  "${AWS[@]}" cloudformation wait stack-delete-complete --stack-name "$CDC_STACK" 2>/dev/null || true
  "${AWS[@]}" cloudformation delete-stack --stack-name "$BROKER_STACK" || true
  "${AWS[@]}" cloudformation delete-stack --stack-name "$TGT_STACK" || true
  "${AWS[@]}" cloudformation delete-stack --stack-name "$SRC_STACK" || true
  "${AWS[@]}" ecs delete-cluster --cluster "$ECS_CLUSTER" 2>/dev/null || true
  c_ok "Delete requested (async). Watch the CloudFormation console for completion."
}

do_benchmark() {
  load_env
  c_step "Initial-load benchmark (parallel bulk load into Valkey)"
  c_ok  "sizes=$BENCH_SIZES workers=$BENCH_WORKERS  (override with CDC_CACHE_BENCH_SIZES / CDC_CACHE_BENCH_WORKERS)"
  printf "\033[33m[note]\033[0m this flushes the target and loads the 'orders' table — it wipes any sample data.\n"
  ( cd "$LOADER_BENCH_DIR"
    python3 initial_load_benchmark.py --sizes "$BENCH_SIZES" --workers "$BENCH_WORKERS" )
  c_ok "Initial-load benchmark done. Compare against docs/benchmarks/01 and 02."
}

do_benchmark_cdc() {
  load_env
  c_step "End-to-end CDC throughput benchmark"
  printf "\033[33m[note]\033[0m REQUIRES the full CDC pipeline already running (Debezium + broker + sink).\n"
  printf "       Deploy it first: ./quickstart.sh cdc (or deploy infra/broker-single.yaml and infra/cdc-ecs.yaml yourself).\n"
  printf "       If the pipeline is not up, this will time out.\n"
  c_ok  "n=$BENCH_CDC_N batch=$BENCH_CDC_BATCH  (override with CDC_CACHE_BENCH_CDC_N / CDC_CACHE_BENCH_CDC_BATCH)"
  ( cd "$LOADER_BENCH_DIR"
    python3 cdc_throughput_bench.py --n "$BENCH_CDC_N" --batch "$BENCH_CDC_BATCH" )
  c_ok "CDC benchmark done. Compare against docs/benchmarks/03 and 04."
}

do_status() {
  for s in "$SRC_STACK" "$TGT_STACK" "$BROKER_STACK" "$CDC_STACK"; do
    local st; st="$("${AWS[@]}" cloudformation describe-stacks --stack-name "$s" \
      --query 'Stacks[0].StackStatus' --output text 2>/dev/null || echo "NOT_FOUND")"
    printf "  %-24s %s\n" "$s" "$st"
  done
}

# ─────────────────────────────────────────────────────────────────────────────
main() {
  local cmd="${1:-all}"
  case "$cmd" in
    all)      preflight; do_deploy; do_seed; do_load; do_verify ;;
    deploy)   preflight; do_deploy ;;
    seed)     preflight; do_seed ;;
    load)     preflight; do_load ;;
    verify)   preflight; do_verify ;;
    cdc)      preflight; do_cdc ;;
    benchmark)     preflight; do_benchmark ;;
    benchmark-cdc) preflight; do_benchmark_cdc ;;
    status)   do_status ;;
    teardown) do_teardown ;;
    *) echo "usage: $0 {all|deploy|seed|load|verify|cdc|benchmark|benchmark-cdc|status|teardown}"; exit 2 ;;
  esac
  c_step "Done: $cmd"
}
main "$@"
