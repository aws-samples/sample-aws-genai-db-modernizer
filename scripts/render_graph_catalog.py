"""Render the graph query catalog into the cookbook (#307).

``src/graph/catalog.py`` is the single source of the questions the context graph
answers. This script writes the catalog's section of
``docs/guides/context-graph-query-cookbook.md``: every entry with its question,
parameters and their choice queries, row bound, needs and a ready-to-post request,
plus the "Empty results" table built from the entries' needs. Only the text
between the two generated-block markers is written; the rest of the cookbook is
edited by hand.

Usage:
    uv run python scripts/render_graph_catalog.py            # write the block
    uv run python scripts/render_graph_catalog.py --check    # exit 1 if it is out of date
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from src.graph.catalog import (  # noqa: E402
    NEEDS,
    SECTIONS,
    CatalogEntry,
    Need,
    Param,
    ParamKind,
    entries,
)
from src.shared.catalog import engine_ids  # noqa: E402

COOKBOOK = REPO_ROOT / "docs" / "guides" / "context-graph-query-cookbook.md"
SCRIPT = "scripts/render_graph_catalog.py"
BEGIN = (
    f"<!-- BEGIN GENERATED by {SCRIPT} from src/graph/catalog.py: "
    "edit the catalog and run the script, never this block -->"
)
END = f"<!-- END GENERATED by {SCRIPT} -->"


#: A line git leaves in a file with an unresolved merge or rebase conflict.
CONFLICT_MARKER = re.compile(r"^(<{7}|={7}|>{7})(?: |$)", re.MULTILINE)


class MarkerError(ValueError):
    """The cookbook has no single pair of block markers, or has conflict markers."""


def _needs_line(entry: CatalogEntry) -> str:
    if not entry.needs:
        return "Needs: nothing beyond the collector."
    return "Needs: " + "; ".join(f"{n.stage} ({n.produces})" for n in entry.needs) + "."


def _graph_view(entry: CatalogEntry) -> str:
    if not entry.projection.nodes:
        return "Graph view: none (a table of counts)."
    labels = {n.column: n.label for n in entry.projection.nodes}
    parts = [f"`{n.label}` (`{n.column}`)" for n in entry.projection.nodes]
    line = "Graph view: nodes " + ", ".join(parts)
    if entry.projection.edges:
        edges = [
            f"`{labels[e.source]}` → `{labels[e.target]}` ({e.label})"
            for e in entry.projection.edges
        ]
        line += "; edges " + ", ".join(edges)
    return line + "."


def _param_line(p: Param) -> str:
    line = f"- `{p.name}` ({p.kind.value}): {p.description} Example `{p.example}`."
    if p.kind is ParamKind.ENGINE:
        # The rule catalog's active engines, so the list follows src/catalog/engines/.
        others = sorted(engine_ids(status="active") - {p.example})
        line += f" Change `{p.example}` to " + ", ".join(f"`{e}`" for e in others) + "."
    return line + f" Choices: `{p.choices_cypher}`"


def _request(entry: CatalogEntry) -> str:
    body: dict[str, object] = {"cypher": entry.cypher}
    if entry.params:
        body["params"] = {p.name: p.example for p in entry.params}
    return json.dumps(body, ensure_ascii=True)


def render_entry(entry: CatalogEntry) -> str:
    lines = [f"### {entry.ref}. {entry.title}", "", entry.question, ""]
    meta = f"Catalog id `{entry.id}`; at most {entry.max_rows:,} rows. {_needs_line(entry)}"
    lines += [meta, "", _graph_view(entry), ""]
    if entry.params:
        lines.append("Parameters:")
        lines.append("")
        lines += [_param_line(p) for p in entry.params]
        lines.append("")
    if entry.note:
        lines += [entry.note, ""]
    lines += ["```json", _request(entry), "```", ""]
    return "\n".join(lines)


def _refs_needing(need: Need) -> list[str]:
    return [e.ref for e in entries() if need in e.needs]


def render_empty_results() -> str:
    lines = [
        "## Empty results",
        "",
        "A query that returns `row_count: 0` usually means the pipeline stage that",
        "produces those nodes has not run for the assessment, not that the query is",
        "wrong. The graph only contains what the artifacts contain. Each entry above",
        "names the stages it needs.",
        "",
        "| Missing | Stage that produces them | Queries |",
        "|---------|--------------------------|---------|",
    ]
    for need in NEEDS:
        refs = _refs_needing(need)
        if refs:
            lines.append(f"| {need.produces} | {need.stage} | {', '.join(refs)} |")
    return "\n".join(lines) + "\n"


def render_block() -> str:
    """The generated block, markers included."""
    parts = [
        BEGIN,
        "",
        "Every query below is an entry of the graph query catalog (`src/graph/catalog.py`).",
        "Each one is a single read statement that passes the raw endpoint's filter, carries",
        "a row bound, and runs against real job fixtures in `tests/graph/test_catalog.py`.",
        "A parameter is bound through `params`, never pasted into the Cypher; its choice",
        "query lists the values the graph holds.",
        "",
    ]
    for section, heading in SECTIONS.items():
        parts += [f"## {heading}", ""]
        parts += [render_entry(e) for e in entries() if e.section == section]
    parts += [render_empty_results(), END]
    return "\n".join(parts) + "\n"


def splice(text: str, block: str) -> str:
    """``text`` with its generated block replaced by ``block``.

    A file with git conflict markers anywhere is refused: the text outside the
    block is merged by hand, and regenerating the block must not hide an
    unresolved conflict next to it.
    """
    conflict = CONFLICT_MARKER.search(text)
    if conflict:
        line = text.count("\n", 0, conflict.start()) + 1
        raise MarkerError(
            f"{COOKBOOK.name}:{line} has a merge conflict marker; resolve the text outside "
            "the generated block by hand, then regenerate the block"
        )
    if text.count(BEGIN) != 1 or text.count(END) != 1:
        raise MarkerError(f"{COOKBOOK.name} needs exactly one BEGIN and one END marker")
    start = text.index(BEGIN)
    end = text.index(END) + len(END)
    if end < start:
        raise MarkerError(f"{COOKBOOK.name}: the END marker comes before BEGIN")
    if text[end : end + 1] == "\n":
        end += 1
    return text[:start] + block + text[end:]


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if the block is stale")
    args = parser.parse_args(argv)
    current = COOKBOOK.read_text(encoding="utf-8") if COOKBOOK.exists() else ""
    try:
        expected = splice(current, render_block())
    except MarkerError as exc:
        print(str(exc))
        return 1
    rel = COOKBOOK.relative_to(REPO_ROOT).as_posix()
    if args.check:
        if current != expected:
            print(f"{rel} out of date. Run: uv run python {SCRIPT}")
            return 1
        print(json.dumps({"render_graph_catalog": "up to date"}))
        return 0
    COOKBOOK.write_text(expected, encoding="utf-8")
    print(json.dumps({"wrote": [rel]}))
    return 0


if __name__ == "__main__":
    sys.exit(main())
