#!/usr/bin/env python3
"""PreToolUse hook (Edit/Write): refuse hand edits of generated baselines (#731).

The routing snapshot, the routing baseline, the contract schema and value-set
snapshots, the ``assess()`` contract's released snapshot and JSON Schemas, the catalog
format snapshot and the release catalog files (#1647) are regenerated by a command,
never by hand: the snapshot commands record why they moved, and the schemas must match
the models they come from. The released snapshot before contract 1.3 is never
regenerated at all: it is the record of what shipped (#1641).
The message names the command. Stdin: the hook event JSON. Exit 0 allows,
exit 2 blocks.
"""

from __future__ import annotations

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import hook_common  # noqa: E402

#: How a protected file that is a record, never regenerated, names its "command".
NEVER_REGENERATE = "never regenerate it"

PROTECTED: dict[str, str] = {
    "tests/e2e/baselines/routing_snapshot.json": (
        'uv run python -m tests.e2e.routing_snapshot --write --reason "why it moved (#NNN)"'
    ),
    "tests/e2e/baselines/routing_baseline.json": (
        'uv run python -m tests.e2e.routing_baseline --write --reason "why it moved (#NNN)"'
    ),
    "tests/contract/schema_snapshot.json": (
        "uv run python scripts/contract_schema_snapshot.py --write"
    ),
    # The public assess() contract's shape at the last release, from 1.3 on (#1641).
    "tests/contract/assess_released_since_1_3.json": (
        "uv run python scripts/contract_schema_snapshot.py --write-released <tag>"
    ),
    # The last release recorded before 1.3 (#1184): a historical record, never re-recorded.
    "tests/contract/assess_released_snapshot.json": (
        NEVER_REGENERATE
        + " (#1641). The current baseline is tests/contract/assess_released_since_1_3.json: "
        "uv run python scripts/contract_schema_snapshot.py --write-released <tag>"
    ),
    # The public assess() request and result schemas (#1183).
    "docs/contracts/schemas/assess_request.v1.schema.json": (
        "uv run python scripts/render_contract_schemas.py --write"
    ),
    "docs/contracts/schemas/assess_result.v1.schema.json": (
        "uv run python scripts/render_contract_schemas.py --write"
    ),
    # The rule catalog's TOML format at the last release (#1647).
    "tests/contract/catalog_format_snapshot.json": (
        "uv run python scripts/catalog_format_snapshot.py --write-released <tag>"
    ),
    "tests/contract/value_set_snapshot.json": (
        "uv run python scripts/contract_value_snapshot.py --write"
    ),
}


#: Directories whose every file is generated (path prefix -> command).
PROTECTED_DIRS: dict[str, str] = {
    # Each release's catalog files, as the tag shipped them (#1647).
    "tests/contract/fixtures/catalog_releases/": (
        "uv run python scripts/catalog_format_snapshot.py --record-files <tag>"
    ),
}


def regeneration_command(file_path: str, cwd: str = "") -> str | None:
    """The command that regenerates ``file_path``, or None when it is not a protected baseline."""
    # Backslash paths (native Windows) are normalised first so the "/" suffix match works.
    full = os.path.normpath(os.path.join(cwd or "", file_path.replace("\\", "/"))).replace(
        "\\", "/"
    )
    for rel, command in PROTECTED.items():
        if full == rel or full.endswith("/" + rel):
            return command
    for prefix, command in PROTECTED_DIRS.items():
        if full.startswith(prefix) or "/" + prefix in full:
            return command
    return None


def main() -> int:
    event = hook_common.read_event()
    file_path = hook_common.tool_input(event).get("file_path")
    if not isinstance(file_path, str) or not file_path:
        return 0
    cwd = event.get("cwd") if isinstance(event.get("cwd"), str) else ""
    command = regeneration_command(file_path, cwd)
    if command is None:
        return 0
    name = os.path.basename(file_path)
    if command.startswith(NEVER_REGENERATE):
        message = f"Blocked: {name} is a historical record; do not edit it by hand, and {command}"
    else:
        message = (
            f"Blocked: {name} is a generated baseline; do not edit it by hand. "
            f"Regenerate it with: {command}"
        )
    return int(hook_common.block(message))


if __name__ == "__main__":
    sys.exit(main())
