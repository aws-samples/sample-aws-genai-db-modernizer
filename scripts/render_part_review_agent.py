"""Render the DynamoDB part-review subagent definition (#2120).

Usage:
    uv run python scripts/render_part_review_agent.py --write | --check

Writes ``.claude/agents/dynamodb-part-review.md``: a subagent whose system prompt
carries everything every DynamoDB part review reads besides its own request --
``.claude/commands/review-schema.md`` from its description on (who runs it, the
steps) and the DynamoDB PE-review skill ``src/skills/dynamodb-pe-review.md`` --
verbatim and in that order.

Why: as for the group drafts (``scripts/render_group_draft_agent.py``, #763), a
subagent's prompt-cache prefix is its system prompt, then its task text, then its
own turns. The part reviews (19 on discourse, again for each redesign round) each
Read the same command and skill after a task naming their part, so each wrote
them to the cache. With them in the system prompt, the first part review writes
them and the others read them (``/modernize`` 6c starts part 1's review first and
the other parts' in the next message).

The other engines' reviews keep the general-purpose subagent: each engine has one
review per design round, with its own skill, so no other review repeats its text.

The file is generated: edit its sources and run this script. ``--check`` exits 1
when the file is stale (``ci/lint.sh`` and a pre-commit hook run it). Stdout is one
JSON line. No model calls.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
AGENT = REPO_ROOT / ".claude" / "agents" / "dynamodb-part-review.md"
COMMAND = REPO_ROOT / ".claude" / "commands" / "review-schema.md"
SKILL = REPO_ROOT / "src" / "skills" / "dynamodb-pe-review.md"
SCRIPT = "scripts/render_part_review_agent.py"
NAME = "dynamodb-part-review"

_HEADER = f"""---
name: {NAME}
description: Reviews one DynamoDB part (group) design for /modernize Phase 6c, /design-schema or /design-schema-dynamodb (the /review-schema steps with the DynamoDB PE-review skill). Dispatched only by those commands, with the part named at the end of the task text.
model: inherit
---

<!-- Generated by {SCRIPT} from {COMMAND.relative_to(REPO_ROOT).as_posix()} and {SKILL.relative_to(REPO_ROOT).as_posix()}. Do not edit: edit those files and run the script with --write. -->

# DynamoDB part review

You review one DynamoDB part design and record the verdict. This prompt is the same for every part, so it is cached once and shared: it carries `/review-schema` and the DynamoDB PE-review skill, in full. Your task text names your review last: its `engine`, `group`, request, response file and `finalize` command.

The command and the skill are below: do not Read `.claude/commands/review-schema.md` or `src/skills/dynamodb-pe-review.md` (the request's `skill_prompt`) again, so step 2's Read is done. Read your request as step 1 says, follow the skill below on its `design`, then do steps 3 and 4.

Do not load `/review-schema` (or any other command or skill) with the Skill tool: this prompt already holds it, and your task text's "Follow /review-schema" means the steps below.

Unattended: do not ask the user anything. Do not dispatch subagents yourself.

## Tool Use

Read files with the Read tool (use `offset`/`limit` for large files). Search file contents with `uv run python scripts/search_artifacts.py <regex> <path>` (or the Grep tool if this session has one). Use Bash only for the documented `uv run python scripts/…` commands; never use `cat`, `jq`, `python3 -c`, `sed`, `ls`, `cd` chains, heredocs or `grep`. Use a search's output as is: never pipe, chain or post-process it.

"""


def _review_command() -> str:
    """``review-schema.md`` without its title and its own Tool Use section (the
    header above carries the same rule)."""
    text = COMMAND.read_text(encoding="utf-8")
    intro = text[text.index("\n") + 1 : text.index("## Tool Use")].strip()
    rest = text[text.index("\n## ", text.index("## Tool Use") + 1) + 1 :].rstrip()
    sections = ("\n" + rest).replace("\n## ", "\n### ").lstrip("\n")
    return "## /review-schema\n\n" + intro + "\n\n" + sections + "\n"


def render() -> str:
    """The agent file's full text."""
    skill = SKILL.read_text(encoding="utf-8").strip()
    return (
        _HEADER
        + _review_command()
        + "\n## The DynamoDB PE-review skill (`src/skills/dynamodb-pe-review.md`)\n\n"
        + "<!-- skill start -->\n\n"
        + skill
        + "\n\n<!-- skill end -->\n"
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0] if __doc__ else None)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true", help="write the agent file")
    mode.add_argument("--check", action="store_true", help="exit 1 if the agent file is stale")
    args = parser.parse_args(argv)
    expected = render()
    rel = AGENT.relative_to(REPO_ROOT).as_posix()
    current = AGENT.read_text(encoding="utf-8") if AGENT.exists() else ""
    if args.check:
        if current != expected:
            print(f"{rel} out of date. Run: uv run python {SCRIPT} --write")
            return 1
        print(json.dumps({"render_part_review_agent": "up to date"}))
        return 0
    AGENT.parent.mkdir(parents=True, exist_ok=True)
    AGENT.write_text(expected, encoding="utf-8")
    print(json.dumps({"wrote": [rel]}))
    return 0


if __name__ == "__main__":
    sys.exit(main())
