"""Render the demo routine scripts of the bundled samples (#1954, ADR-034).

Each MySQL and PostgreSQL sample keeps a small synthetic routine set next to its zip,
``docs/examples/<sample>/<sample>-routines.json``, in the sections the collection script
writes; the deterministic e2e adds it to the collection. For the step 1 rehearsal the
same set has to exist on the sample's own source database, so a collection taken there
holds it and step 1 carries it to the rehearsal Aurora. This script writes, from the
JSON set and nothing else:

- ``<sample>-routines-install.sql``: creates every routine of the set on the source, in
  dependency order (functions, procedures, triggers, events), each ``CREATE`` exactly as
  the routine sources build it from the set (``build_routine_sources``), under the
  session or owner the set records;
- ``<sample>-routines-remove.sql``: drops them again, in the reverse order.

The texts are synthetic, so both files are public. The customer, or the maintainer for
the rehearsal, runs them; nothing here connects to a database.

Usage:
    uv run python scripts/render_sample_routines.py            # write the files
    uv run python scripts/render_sample_routines.py --check    # exit 1 if one is stale
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

REPO_ROOT = Path(__file__).resolve().parent.parent
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from src.agents.collector.mysql_routine_create import quote_ident, string_literal  # noqa: E402
from src.agents.collector.routine_sources import build_routine_sources  # noqa: E402

#: Each sample with a routine set, its source engine and its source database.
SAMPLES: dict[str, tuple[str, str]] = {
    "wordpress": ("mysql", "wordpress"),
    "discourse": ("postgresql", "discourse"),
}
#: The order the install creates each kind in: a routine follows what it calls.
KIND_ORDER = ("function", "procedure", "trigger", "event")


def routine_set(sample: str) -> dict[str, Any]:
    path = REPO_ROOT / "docs" / "examples" / sample / f"{sample}-routines.json"
    data: dict[str, Any] = json.loads(path.read_text(encoding="utf-8"))
    return data


def _sources(sample: str) -> list[Any]:
    engine, _ = SAMPLES[sample]
    data = routine_set(sample)
    build = build_routine_sources(
        engine,
        procedures=data.get("procedures") or [],
        triggers=data.get("triggers") or [],
        events=data.get("events") or [],
        parameters=data.get("routine_parameters") or [],
    )
    if build.statuses:
        raise ValueError(
            f"{sample}: the set has routines with no loadable CREATE: {build.statuses}"
        )
    return sorted(build.sources, key=lambda s: KIND_ORDER.index(s.kind))


def _header(sample: str, purpose: str) -> list[str]:
    engine, database = SAMPLES[sample]
    return [
        "-- Copyright Amazon.com, Inc. or its affiliates. All Rights Reserved.",
        "-- SPDX-License-Identifier: MIT-0",
        "--",
        f"-- {sample}-routines-{purpose}.sql: the synthetic routine set of the {sample} sample.",
        f"-- Generated by scripts/render_sample_routines.py from {sample}-routines.json.",
        "-- Do not edit by hand: change the JSON set and render again.",
        f"-- Run it on the sample's {engine_name(engine)} source, in the `{database}` database.",
    ]


def engine_name(engine: str) -> str:
    return {"mysql": "MySQL", "postgresql": "PostgreSQL"}[engine]


# --- MySQL --------------------------------------------------------------------------


def _mysql_name(source: Any) -> str:
    return quote_ident(source.routine_id)


def _mysql_session(source: Any) -> list[str]:
    """The session the routine was created under, as the routine sources record it: its
    character set and collation, its time zone (an event's), then its sql_mode."""
    s = source.session
    out = []
    if s.character_set_client is not None and s.collation_connection is not None:
        out.append(
            f"SET NAMES {string_literal(s.character_set_client, '')} "
            f"COLLATE {string_literal(s.collation_connection, '')}$$"
        )
    if s.time_zone is not None:
        out.append(f"SET SESSION time_zone = {string_literal(s.time_zone, '')}$$")
    if s.sql_mode is not None:
        out.append(f"SET SESSION sql_mode = {string_literal(s.sql_mode, '')}$$")
    return out


def _mysql_drop(source: Any) -> str:
    kind = source.kind.upper()
    return f"DROP {kind} IF EXISTS {_mysql_name(source)}$$"


def _mysql_install(sample: str) -> str:
    lines = _header(sample, "install") + [
        "--",
        "-- Run it with the mysql client as the master user `admin`, which every routine but",
        "-- one names as its DEFINER. wp_refresh_comment_count names `wp_user`@`localhost`,",
        "-- so the run shows its DEFINER rewrite; creating it needs the SET_USER_ID privilege.",
        "-- Once installed, the trigger adds 1 to a post's comment_count on each new comment,",
        "-- and the event, with the event scheduler on, deletes Action Scheduler log rows",
        "-- older than 30 days once a day. Remove them with the remove script.",
        "-- Each object is dropped first, so the script can run again.",
        "",
        "DELIMITER $$",
    ]
    for source in _sources(sample):
        lines += ["", f"-- {source.kind} {source.routine_id}"]
        lines += _mysql_session(source)
        lines.append(_mysql_drop(source))
        lines.append(f"{source.create_statement.rstrip()}$$")
    lines += ["", "DELIMITER ;", ""]
    return "\n".join(lines)


def _mysql_remove(sample: str) -> str:
    lines = _header(sample, "remove") + ["", "DELIMITER $$"]
    for source in reversed(_sources(sample)):
        lines.append(_mysql_drop(source))
    lines += ["DELIMITER ;", ""]
    return "\n".join(lines)


# --- PostgreSQL ---------------------------------------------------------------------


def _pg_signature(row: dict[str, Any]) -> str:
    """``public.name(argument types)`` for ``ALTER``/``DROP``: the identity arguments
    with their modes and names, which PostgreSQL accepts there."""
    return f"{row['schema_name']}.{row['routine_name']}({row['identity_arguments']})"


def _pg_rows(sample: str) -> dict[tuple[str, str], dict[str, Any]]:
    """Each routine row of the set by (kind, specific name), as the sources name them."""
    return {
        (str(r["routine_type"]).lower(), str(r["specific_name"])): r
        for r in routine_set(sample).get("procedures") or []
    }


def _pg_triggers(sample: str) -> dict[str, dict[str, Any]]:
    return {str(t["trigger_name"]): t for t in routine_set(sample).get("triggers") or []}


def _pg_drop(sample: str, source: Any) -> str:
    if source.kind == "trigger":
        t = _pg_triggers(sample)[source.routine_id]
        return (
            f"DROP TRIGGER IF EXISTS {source.routine_id} ON {t['schema_name']}.{t['table_name']};"
        )
    row = _pg_rows(sample)[(source.kind, source.specific_name)]
    return f"DROP {source.kind.upper()} IF EXISTS {_pg_signature(row)};"


def _pg_install(sample: str) -> str:
    owners = sorted({str(r["owner"]) for r in _pg_rows(sample).values()})
    lines = _header(sample, "install") + [
        "--",
        f"-- Run it with psql as a user that may give its routines to the roles {', '.join(owners)},",
        "-- the owners the set records. posts_bump_topic() is owned by discourse, so the run",
        "-- shows its owner rewrite. The tables it reads must exist: run it after the sample's",
        "-- schema is loaded. Once installed, the trigger sets a topic's bumped_at on each new",
        "-- post. Remove the set with the remove script. It runs in one transaction and can",
        "-- run again.",
        "",
        "\\set ON_ERROR_STOP on",
        "BEGIN;",
    ]
    for source in _sources(sample):
        lines += ["", f"-- {source.kind} {source.schema_name}.{source.routine_id}"]
        if source.kind == "trigger":
            lines.append(_pg_drop(sample, source))
            lines.append(f"{source.create_statement.rstrip().rstrip(';')};")
            continue
        lines.append(source.create_statement.rstrip().rstrip(";") + ";")
        row = _pg_rows(sample)[(source.kind, source.specific_name)]
        lines.append(f"ALTER {source.kind.upper()} {_pg_signature(row)} OWNER TO {row['owner']};")
    lines += ["", "COMMIT;", ""]
    return "\n".join(lines)


def _pg_remove(sample: str) -> str:
    lines = _header(sample, "remove") + ["", "\\set ON_ERROR_STOP on", "BEGIN;"]
    for source in reversed(_sources(sample)):
        lines.append(_pg_drop(sample, source))
    lines += ["COMMIT;", ""]
    return "\n".join(lines)


def outputs() -> list[tuple[Path, str]]:
    out: list[tuple[Path, str]] = []
    for sample, (engine, _) in SAMPLES.items():
        folder = REPO_ROOT / "docs" / "examples" / sample
        install, remove = (
            (_mysql_install, _mysql_remove) if engine == "mysql" else (_pg_install, _pg_remove)
        )
        out.append((folder / f"{sample}-routines-install.sql", install(sample)))
        out.append((folder / f"{sample}-routines-remove.sql", remove(sample)))
    return out


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=(__doc__ or "").splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if a file is stale")
    args = parser.parse_args(argv)
    rendered = outputs()
    if args.check:
        stale = [
            path.relative_to(REPO_ROOT).as_posix()
            for path, text in rendered
            if (path.read_text(encoding="utf-8") if path.exists() else "") != text
        ]
        if stale:
            print(
                json.dumps(
                    {"stale": stale, "fix": "uv run python scripts/render_sample_routines.py"}
                )
            )
            return 1
        print(json.dumps({"render_sample_routines": "up to date"}))
        return 0
    for path, text in rendered:
        path.write_text(text, encoding="utf-8")
    print(json.dumps({"wrote": [path.relative_to(REPO_ROOT).as_posix() for path, _ in rendered]}))
    return 0


if __name__ == "__main__":
    sys.exit(main())
