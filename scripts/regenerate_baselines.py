#!/usr/bin/env python3
"""Regenerate every generated baseline with one command, and say which is stale (#1163).

The baselines are generated files that a rebase or a deliberate change leaves stale.
Each is regenerated by its own documented script, never by hand and never by merging two
versions of the file:

* routing snapshot and routing baseline (``tests/e2e/baselines/``): the deterministic
  pipeline on every bundled sample; the commands need ``--reason``
* contract schema snapshot and value-set snapshot (``tests/contract/``)
* the ``assess()`` JSON Schemas (``docs/contracts/schemas/``)
* the rendered rule catalog (``docs/architecture/rule-catalog.md`` and the UI's
  ``engineCatalog.generated.js``)

Not covered: ``tests/contract/assess_released_snapshot.json`` is recorded at a release
(``scripts/contract_schema_snapshot.py --write-released <tag>``), never on a rebase.

Usage::

    uv run python scripts/regenerate_baselines.py --check            # name the stale ones, exit 1
    uv run python scripts/regenerate_baselines.py --reason "why (#N)"  # regenerate the stale ones
    uv run python scripts/regenerate_baselines.py --only catalog     # just one (repeatable)

A baseline that is already fresh is left alone, so running this on a clean tree changes
nothing (the routing commands append to a history on every write). The contract
snapshots count as fresh while a pending bump (``scripts/bump_contract.py``) covers the
change, exactly as their tests do.
"""

from __future__ import annotations

import argparse
import subprocess  # nosec B404 -- fixed argv built from this file's own constants
import sys
import tempfile
from collections.abc import Callable, Sequence
from dataclasses import dataclass
from pathlib import Path

from defusedxml import ElementTree as ET  # the junit file this script just wrote

REPO = Path(__file__).resolve().parent.parent
if str(REPO) not in sys.path:
    sys.path.insert(0, str(REPO))

REASON_PLACEHOLDER = "why it moved (#NNN)"
SELF_COMMAND = "uv run python scripts/regenerate_baselines.py"


@dataclass(frozen=True)
class Baseline:
    name: str
    files: tuple[str, ...]
    command: str  # the documented command, as a person types it
    write_argv: Callable[[str], list[str]]  # argv (after the interpreter) given the reason
    is_stale: Callable[[], bool]
    needs_reason: bool = False


def _python(*args: str) -> list[str]:
    return [sys.executable, *args]


def _check_script_is_stale(script: str, flag: str = "--check") -> bool:
    return (
        subprocess.run(  # nosec B603 -- fixed argv
            _python(str(REPO / "scripts" / script), flag),
            cwd=REPO,
            capture_output=True,
            check=False,
        ).returncode
        != 0
    )


def _contract_schema_stale() -> bool:
    import json

    from scripts.contract_bumps import load_pending, pending_kinds
    from scripts.contract_schema_snapshot import SNAPSHOT_PATH, build_snapshot, evaluate_snapshot

    if not SNAPSHOT_PATH.exists():
        return True
    committed = json.loads(SNAPSHOT_PATH.read_text())
    return bool(evaluate_snapshot(committed, build_snapshot(), pending_kinds(load_pending())))


def _value_set_stale() -> bool:
    import json

    from scripts.contract_bumps import load_pending, pending_kinds, pending_module_kinds
    from scripts.contract_value_snapshot import SNAPSHOT_PATH, build_snapshot, evaluate_snapshot

    if not SNAPSHOT_PATH.exists():
        return True
    committed = json.loads(SNAPSHOT_PATH.read_text())
    pending = pending_module_kinds(pending_kinds(load_pending()))
    return bool(evaluate_snapshot(committed, build_snapshot(), pending))


# name -> (guard test file, test name prefix, text of the guard's drift failure). Only a failure
# that carries the drift text means the baseline is stale; any other failure (a crash, a changed
# assertion) stops the run instead, so --reason never overwrites a baseline over a real bug.
_ROUTING_TESTS = {
    "routing-snapshot": (
        "tests/e2e/test_routing_snapshot.py",
        "test_routing_snapshot_matches",
        "The snapshot is out of date",
    ),
    "routing-baseline": (
        "tests/e2e/test_routing_baseline.py",
        "test_routing_shape_matches",
        "routing moved beyond the baseline",
    ),
}
_routing_cache: dict[str, bool] = {}


def routing_staleness_from_junit(xml_text: str) -> dict[str, bool]:
    """Per routing baseline: True when its guard failed on drift, False when it passed.

    Raises RuntimeError when a guard did not run, errored, or failed for another reason."""
    root = ET.fromstring(xml_text)
    cases = list(root.iter("testcase"))
    result: dict[str, bool] = {}
    for key, (file, prefix, drift_text) in _ROUTING_TESTS.items():
        mine = [
            c
            for c in cases
            if c.get("classname", "").endswith(Path(file).stem)
            and c.get("name", "").startswith(prefix)
        ]
        by_hand = f"run it by hand to see why: uv run pytest {file} -p no:xdist -q"
        if not mine or any(c.find("error") is not None for c in mine):
            raise RuntimeError(f"could not run the {key} guard ({file}); {by_hand}")
        failures = [f for f in (c.find("failure") for c in mine) if f is not None]
        for failure in failures:
            if drift_text not in f"{failure.get('message', '')}\n{failure.text or ''}":
                raise RuntimeError(
                    f"the {key} guard failed, but not with its drift message ({drift_text!r}), "
                    f"so the baseline is not regenerated; {by_hand}"
                )
        result[key] = bool(failures)
    return result


def _routing_stale(name: str) -> bool:
    """Whether the routing guard for ``name`` fails on drift, from one pytest run of both."""
    if not _routing_cache:
        with tempfile.TemporaryDirectory() as tmp:
            junit = Path(tmp) / "routing.xml"
            subprocess.run(  # nosec B603 -- fixed argv
                _python(
                    "-m",
                    "pytest",
                    *sorted({file for file, _, _ in _ROUTING_TESTS.values()}),
                    "-k",
                    " or ".join(prefix for _, prefix, _ in _ROUTING_TESTS.values()),
                    "-p",
                    "no:xdist",
                    "-p",
                    "no:cacheprovider",
                    "-q",
                    f"--junitxml={junit}",
                ),
                cwd=REPO,
                capture_output=True,
                check=False,
            )
            if not junit.exists():
                raise RuntimeError(
                    "pytest wrote no result for the routing guards; run them by hand"
                )
            _routing_cache.update(routing_staleness_from_junit(junit.read_text(encoding="utf-8")))
    return _routing_cache[name]


BASELINES: tuple[Baseline, ...] = (
    Baseline(
        "catalog",
        ("docs/architecture/rule-catalog.md", "src/ui/src/utils/engineCatalog.generated.js"),
        "uv run python scripts/render_catalog.py",
        lambda _reason: _python("scripts/render_catalog.py"),
        lambda: _check_script_is_stale("render_catalog.py"),
    ),
    Baseline(
        "assess-schemas",
        (
            "docs/contracts/schemas/assess_request.v1.schema.json",
            "docs/contracts/schemas/assess_result.v1.schema.json",
        ),
        "uv run python scripts/render_contract_schemas.py --write",
        lambda _reason: _python("scripts/render_contract_schemas.py", "--write"),
        lambda: _check_script_is_stale("render_contract_schemas.py"),
    ),
    Baseline(
        "contract-schema-snapshot",
        ("tests/contract/schema_snapshot.json",),
        "uv run python scripts/contract_schema_snapshot.py --write",
        lambda _reason: _python("scripts/contract_schema_snapshot.py", "--write"),
        _contract_schema_stale,
    ),
    Baseline(
        "value-set-snapshot",
        ("tests/contract/value_set_snapshot.json",),
        "uv run python scripts/contract_value_snapshot.py --write",
        lambda _reason: _python("scripts/contract_value_snapshot.py", "--write"),
        _value_set_stale,
    ),
    Baseline(
        "routing-baseline",
        ("tests/e2e/baselines/routing_baseline.json",),
        f'uv run python -m tests.e2e.routing_baseline --write --reason "{REASON_PLACEHOLDER}"',
        lambda reason: _python("-m", "tests.e2e.routing_baseline", "--write", "--reason", reason),
        lambda: _routing_stale("routing-baseline"),
        needs_reason=True,
    ),
    Baseline(
        "routing-snapshot",
        ("tests/e2e/baselines/routing_snapshot.json",),
        f'uv run python -m tests.e2e.routing_snapshot --write --reason "{REASON_PLACEHOLDER}"',
        lambda reason: _python("-m", "tests.e2e.routing_snapshot", "--write", "--reason", reason),
        lambda: _routing_stale("routing-snapshot"),
        needs_reason=True,
    ),
)


def _run(argv: list[str]) -> int:
    return subprocess.run(argv, cwd=REPO, check=False).returncode  # nosec B603 -- fixed argv


def main(
    argv: Sequence[str] | None = None,
    baselines: Sequence[Baseline] = BASELINES,
    run: Callable[[list[str]], int] = _run,
) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--check",
        action="store_true",
        help="write nothing; name the stale baselines and their commands; exit 1 if any",
    )
    parser.add_argument(
        "--only",
        action="append",
        default=[],
        metavar="NAME",
        help=f"limit to one baseline (repeatable): {', '.join(b.name for b in baselines)}",
    )
    parser.add_argument(
        "--reason",
        default="",
        help="why the routing baselines moved; required when a routing baseline is stale",
    )
    args = parser.parse_args(argv)
    known = {b.name for b in baselines}
    unknown = sorted(set(args.only) - known)
    if unknown:
        parser.error(
            f"unknown baseline(s) {', '.join(unknown)}; choose from {', '.join(sorted(known))}"
        )
    selected = [b for b in baselines if not args.only or b.name in args.only]

    stale: list[Baseline] = []
    for baseline in selected:
        try:
            is_stale = baseline.is_stale()
        except RuntimeError as exc:
            print(f"error: {exc}", file=sys.stderr)
            return 2
        if is_stale:
            stale.append(baseline)
            print(f"stale: {baseline.name} ({', '.join(baseline.files)})")
            print(f"       regenerate with: {baseline.command}")
        else:
            print(f"fresh: {baseline.name}")
    if not stale:
        print("every generated baseline is fresh")
        return 0

    reason = args.reason.strip()
    if args.check:
        print(f"stale baselines: {', '.join(b.name for b in stale)}")
        print(f'regenerate all of them: {SELF_COMMAND} --reason "{REASON_PLACEHOLDER}"')
        return 1

    needing_reason = [b.name for b in stale if b.needs_reason]
    if needing_reason and not reason:
        print(
            f"error: --reason is required to regenerate {', '.join(needing_reason)}: say why "
            f'the routing moved, e.g. --reason "{REASON_PLACEHOLDER}". Nothing was written.',
            file=sys.stderr,
        )
        return 2
    for baseline in stale:
        print(f"regenerating {baseline.name}: {baseline.command}")
        sys.stdout.flush()  # keep this line ahead of the child's output
        code = run(baseline.write_argv(reason))
        if code != 0:
            print(
                f"error: {baseline.name} failed (exit {code}); later baselines were not regenerated",
                file=sys.stderr,
            )
            return code
    print(f"regenerated: {', '.join(b.name for b in stale)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
