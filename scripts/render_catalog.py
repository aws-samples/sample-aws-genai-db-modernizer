#!/usr/bin/env python3
"""Render the UI's engine tables from the engine catalog (ADR-031 Decision 8, #492).

``src/catalog/engines/*.toml`` is the single source of the engine facts every consumer
must agree on. Python reads it through ``src.shared.catalog``; the UI cannot read TOML
at run time, so this script writes the facts it uses into one generated module,
``src/ui/src/utils/engineCatalog.generated.js``, which ``engineNames.js``,
``cacheLayer.js``, ``ChartSankey-01.js`` and ``AssignmentGate.js`` import.

Usage:
    uv run python scripts/render_catalog.py            # write the generated module
    uv run python scripts/render_catalog.py --check    # exit 1 if it is out of date
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from src.shared.catalog import ACTIVE, EngineEntry, engine_ids, engines  # noqa: E402

JS_OUT = REPO_ROOT / "src" / "ui" / "src" / "utils" / "engineCatalog.generated.js"

BANNER = (
    "// GENERATED by scripts/render_catalog.py from src/catalog/engines/*.toml -- do not edit.\n"
    "// Change the engine's TOML file, then run: uv run python scripts/render_catalog.py\n"
)


def _js_string(value: str) -> str:
    # Single-quoted, the repo's JS style; json.dumps does the escaping.
    return "'" + json.dumps(value)[1:-1].replace("'", "\\'") + "'"


def _object(name: str, doc: str, rows: list[tuple[str, str]]) -> str:
    body = "".join(f"  {key}: {_js_string(value)},\n" for key, value in rows)
    return f"// {doc}\nexport const {name} = {{\n{body}}};\n"


def render_js(entries: tuple[EngineEntry, ...]) -> str:
    """The generated module's full text for ``entries`` (in catalog display order)."""
    cache_ids = sorted(engine_ids(status=ACTIVE, role="cache"))
    parts = [
        BANNER,
        _object(
            "ENGINE_LABELS",
            "Display name per engine id (display_name).",
            [(e.id, e.display_name) for e in entries],
        ),
        _object(
            "ENGINE_HEX",
            "Live UI colour per engine id (colors.ui).",
            [(e.id, e.colors.ui) for e in entries],
        ),
        _object(
            "ENGINE_BADGE_COLORS",
            "Live UI badge colour per engine id (colors.ui_badge).",
            [(e.id, e.colors.ui_badge) for e in entries],
        ),
        "// Every engine id in the assignment gate's picker order (ui_picker_order).\n"
        "export const ENGINE_PICKER_ORDER = ["
        + ", ".join(_js_string(e.id) for e in sorted(entries, key=lambda e: e.ui_picker_order))
        + "];\n",
        '// Active engines whose role is a cache layer (role = "cache").\n'
        f"export const CACHE_ENGINE_IDS = [{', '.join(_js_string(i) for i in cache_ids)}];\n",
    ]
    return "\n".join(parts)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if the module is stale")
    args = parser.parse_args(argv)
    expected = render_js(engines())
    if args.check:
        current = JS_OUT.read_text(encoding="utf-8") if JS_OUT.exists() else ""
        if current != expected:
            rel = JS_OUT.relative_to(REPO_ROOT)
            print(f"{rel} is out of date. Run: uv run python scripts/render_catalog.py")
            return 1
        print(json.dumps({"render_catalog": "up to date"}))
        return 0
    JS_OUT.write_text(expected, encoding="utf-8")
    print(json.dumps({"wrote": str(JS_OUT.relative_to(REPO_ROOT))}))
    return 0


if __name__ == "__main__":
    sys.exit(main())
