"""Render the DynamoDB group-draft subagent definition (#355 item 2, #763).

Usage:
    uv run python scripts/render_group_draft_agent.py --write | --check

Writes ``.claude/agents/dynamodb-group-draft.md``: a subagent whose system prompt
carries everything every DynamoDB group draft reads before its own slice -- the
**Group draft task** section of ``.claude/commands/design-schema-dynamodb.md``,
the data-modeling skill ``src/skills/dynamodb-data-modeling.md`` and the output
contract ``src/contracts/dynamodb_model_output.py`` -- verbatim and in that order.

Why: a subagent's prompt-cache prefix is its system prompt, then its task text,
then its own turns. Group subagents that each Read the shared files after a
task text naming their group write the same ~25K tokens to the cache once per
group. With the shared material in the system prompt, the first group writes it
and every later group reads it (``/modernize`` 6b starts part 1 first and the
other parts in the next message, so the entry exists when they start). The task
text then carries only what differs per group, last.

The file is generated: edit its sources and run this script. ``--check`` exits 1
when the file is stale (``ci/lint.sh`` and a pre-commit hook run it). Stdout is one
JSON line. No model calls.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
AGENT = REPO_ROOT / ".claude" / "agents" / "dynamodb-group-draft.md"
COMMAND = REPO_ROOT / ".claude" / "commands" / "design-schema-dynamodb.md"
SKILL = REPO_ROOT / "src" / "skills" / "dynamodb-data-modeling.md"
CONTRACT = REPO_ROOT / "src" / "contracts" / "dynamodb_model_output.py"
SCRIPT = "scripts/render_group_draft_agent.py"
NAME = "dynamodb-group-draft"

_HEADER = f"""---
name: {NAME}
description: Writes one DynamoDB group draft for /modernize Phase 6 or /design-schema-dynamodb (the Group draft task). Dispatched only by those commands, with the group named at the end of the task text.
model: inherit
---

<!-- Generated by {SCRIPT} from {COMMAND.relative_to(REPO_ROOT).as_posix()} (Group draft task), {SKILL.relative_to(REPO_ROOT).as_posix()} and {CONTRACT.relative_to(REPO_ROOT).as_posix()}. Do not edit: edit those files and run the script with --write. -->

# DynamoDB group draft

You write one DynamoDB group draft. This prompt is the same for every group, so it is cached once and shared: it carries the **Group draft task** of `/design-schema-dynamodb`, the data-modeling skill and the output contract, in full. Your task text names your group last: its `group`, input file and Read pages, the other groups' `primary_tables` and the one draft file you write.

The skill and the contract are below: do not Read `src/skills/dynamodb-data-modeling.md`, `src/contracts/dynamodb_model_output.py` or `.claude/commands/design-schema-dynamodb.md` again (Group draft task steps 2 and 3 are done). Read your group input as step 1 says, then follow steps 4-7.

Do not load `/design-schema-dynamodb` (or any other command or skill) with the Skill tool: this prompt already holds the task, and your task text's "Follow /design-schema-dynamodb **Group draft task**" means the section below.

Unattended: do not ask the user anything. Do not dispatch subagents yourself.

## Tool Use

Read files with the Read tool (use `offset`/`limit` for large files). Search file contents with `uv run python scripts/search_artifacts.py <regex> <path>` (or the Grep tool if this session has one). Use Bash only for the documented `uv run python scripts/…` commands; never use `cat`, `jq`, `python3 -c`, `sed`, `ls`, `cd` chains, heredocs or `grep`. Use a search's output as is: never pipe, chain or post-process it.

"""


def _group_draft_task() -> str:
    text = COMMAND.read_text(encoding="utf-8")
    start = text.index("## Group draft task")
    end = text.index("\n## ", start + 1)
    return text[start:end].rstrip() + "\n"


def render() -> str:
    """The agent file's full text."""
    skill = SKILL.read_text(encoding="utf-8").strip()
    contract = CONTRACT.read_text(encoding="utf-8").rstrip()
    return (
        _HEADER
        + _group_draft_task()
        + "\n## The data-modeling skill (`src/skills/dynamodb-data-modeling.md`)\n\n"
        + "<!-- skill start -->\n\n"
        + skill
        + "\n\n<!-- skill end -->\n"
        + "\n## The output contract (`src/contracts/dynamodb_model_output.py`)\n\n"
        + "````python\n"
        + contract
        + "\n````\n"
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0] if __doc__ else None)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true", help="write the agent file")
    mode.add_argument("--check", action="store_true", help="exit 1 if the agent file is stale")
    args = parser.parse_args(argv)
    expected = render()
    rel = AGENT.relative_to(REPO_ROOT).as_posix()
    current = AGENT.read_text(encoding="utf-8") if AGENT.exists() else ""
    if args.check:
        if current != expected:
            print(f"{rel} out of date. Run: uv run python {SCRIPT} --write")
            return 1
        print(json.dumps({"render_group_draft_agent": "up to date"}))
        return 0
    AGENT.parent.mkdir(parents=True, exist_ok=True)
    AGENT.write_text(expected, encoding="utf-8")
    print(json.dumps({"wrote": [rel]}))
    return 0


if __name__ == "__main__":
    sys.exit(main())
