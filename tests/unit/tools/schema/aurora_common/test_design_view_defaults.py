"""The design view shows the draft's column defaults, not the collector's (#611).

The model designs a delta for the draft DDL, so each column line must agree with
that DDL: ``AI`` where the draft made the column an identity column, the translated
``DEFAULT`` the draft kept, and a short "default dropped" marker where it dropped one
(the reason stays in ``column_notes``). Raw collector text never reaches the line.
"""

from __future__ import annotations

from datetime import UTC, datetime

import pytest

from src.contracts.schema_design_input import AgentCollectorInput
from src.tools.schema.aurora_common.delta_merge import AuroraDesignBase
from src.tools.schema.aurora_common.design_view import build_design_view

PG = "aurora_postgresql"
MY = "aurora_mysql"


def _collector(source_engine: str, columns: list[dict]) -> AgentCollectorInput:
    return AgentCollectorInput.model_validate(
        {
            "contract_version": "3.0.0",
            "job_id": "j",
            "source_database_name": "shop",
            "source_database_engine": source_engine,
            "collection_timestamp": datetime(2026, 1, 1, tzinfo=UTC),
            "tables": [
                {
                    "table_id": "shop.orders",
                    "table_name": "orders",
                    "row_count": 10,
                    "primary_key": ["id"],
                    "columns": columns,
                }
            ],
            "queries": {"query_patterns": []},
        }
    )


def _lines(engine: str, source_engine: str, columns: list[dict]) -> tuple[dict, str, dict]:
    collector = _collector(source_engine, columns)
    base = AuroraDesignBase.from_inputs(engine, collector)
    view = build_design_view(base, collector)
    by_name = {line.split()[0].strip('"`'): line for line in view["tables"][0]["columns"]}
    return by_name, base.generate().full_ddl, view


# SQL Server columns reach the draft through their normalized type.
SQLSERVER_COLUMNS = [
    {
        "column_name": "id",
        "data_type": "bigint",
        "normalized_data_type": "integer",
        "nullable": False,
        "default_value": "(NEXT VALUE FOR [dbo].[order_seq])",
    },
    {
        "column_name": "who",
        "data_type": "varchar",
        "normalized_data_type": "string",
        "max_length": 50,
        "nullable": True,
        "default_value": "(suser_sname())",
    },
    {
        "column_name": "qty",
        "data_type": "int",
        "normalized_data_type": "integer",
        "nullable": False,
        "default_value": "((0))",
    },
    {
        "column_name": "note",
        "data_type": "varchar",
        "normalized_data_type": "string",
        "max_length": 20,
        "nullable": True,
    },
]


def test_the_issue_repro_matches_the_draft_ddl():
    lines, ddl, view = _lines(PG, "sqlserver", SQLSERVER_COLUMNS)

    assert "GENERATED BY DEFAULT AS IDENTITY" in ddl
    assert lines["id"] == "id BIGINT NOT NULL AI"
    assert lines["who"].endswith("(default dropped)")
    assert lines["qty"].endswith("NOT NULL DEFAULT 0")
    assert "DEFAULT" not in lines["note"]
    for line in lines.values():
        assert "NEXT VALUE FOR" not in line and "suser_sname" not in line
        assert "((0))" not in line
    # the reason the draft dropped or rewrote a default stays in column_notes
    noted = {n["column"] for n in view["column_notes"] if n["kind"] == "default"}
    assert {"id", "who"} <= noted


@pytest.mark.parametrize(
    "engine,source,default,shown",
    [
        (PG, "postgresql", "now()", "DEFAULT CURRENT_TIMESTAMP"),
        (PG, "postgresql", "'open'::character varying", "DEFAULT 'open'"),
        (MY, "mysql", "CURRENT_TIMESTAMP", "DEFAULT CURRENT_TIMESTAMP"),
        (MY, "mysql", "open", "DEFAULT 'open'"),
    ],
)
def test_a_kept_default_shows_the_translated_clause(engine, source, default, shown):
    data_type = "timestamp" if "TIMESTAMP" in shown else "varchar"
    columns = [
        {"column_name": "id", "data_type": "bigint", "nullable": False},
        {
            "column_name": "c",
            "data_type": data_type,
            "max_length": 20,
            "nullable": True,
            "default_value": default,
        },
    ]
    lines, ddl, _ = _lines(engine, source, columns)
    assert lines["c"].endswith(shown)
    assert shown in ddl


@pytest.mark.passes_on_main  # guards what #611 must keep
def test_a_source_auto_increment_column_still_reads_ai():
    columns = [
        {"column_name": "id", "data_type": "bigint", "nullable": False, "is_auto_increment": True}
    ]
    lines, _, _ = _lines(MY, "mysql", columns)
    assert lines["id"] == "id BIGINT NOT NULL AI"


def test_a_long_kept_default_is_truncated_in_the_view_only():
    text = "x" * 60
    columns = [
        {"column_name": "id", "data_type": "bigint", "nullable": False},
        {
            "column_name": "c",
            "data_type": "varchar",
            "max_length": 100,
            "nullable": True,
            "default_value": text,
        },
    ]
    lines, ddl, _ = _lines(MY, "mysql", columns)
    # 40 characters of the value itself, as before #611: the quote and 39 x's
    assert lines["c"].endswith("DEFAULT '" + "x" * 39 + "...")
    assert f"DEFAULT '{text}'" in ddl


def test_a_null_default_the_draft_omits_is_not_called_dropped():
    # DEFAULT NULL on a NOT NULL column is simply omitted: nothing was lost, no note.
    columns = [
        {"column_name": "id", "data_type": "bigint", "nullable": False},
        {
            "column_name": "c",
            "data_type": "varchar",
            "max_length": 9,
            "nullable": False,
            "default_value": "NULL",
        },
    ]
    lines, _, _ = _lines(PG, "postgresql", columns)
    assert lines["c"] == "c VARCHAR(9) NOT NULL"
