def _sample_tables(name: str) -> list[AgentTable]:
    from src.agents.collector.mysql_collector import _build_tables
    from src.tools.database.offline_parser import parse_offline_collection

    archive = _ROOT / "docs" / "examples" / name / f"{name}.zip"
    with zipfile.ZipFile(archive) as zf:
        content = zf.read(f"{name}-collection.json").decode().strip()
    if not content.startswith("{"):  # mysql client header line ("collection_output")
        content = content[content.index("\n") + 1 :]
    raw = json.loads(content)
    parsed = parse_offline_collection(raw)
    built = _build_tables(parsed["tables"], name)
    return [AgentTable.model_validate(t.model_dump(mode="json")) for t in built]


@pytest.fixture(scope="module")
def discourse_tables() -> list[AgentTable]:
    return _sample_tables("discourse")


def test_discourse_carry_over_residuals_drop_to_the_genuinely_unmappable(discourse_tables):
    before = generate_pg_ddl(discourse_tables)  # normalized type only (pre-#274)
    after = generate_pg_ddl(discourse_tables, source_engine="postgresql")

    assert len(before.residuals) > 1500
    # Only the two PostgreSQL enum types remain: their CREATE TYPE is not collected.
    assert sorted(r["source_type"] for r in after.residuals) == [
        "ai_moderation_setting_type",
        "hotlinked_media_status",
    ]
    ids = {(t.table_name, c.name): c.aurora_type for t in after.tables for c in t.columns}
    assert ids[("admin_notices", "id")] == "BIGINT"


def test_wordpress_carry_over_has_no_residuals():
    tables = _sample_tables("wordpress")
    result = generate_mysql_ddl(tables, source_engine="mysql")
    assert result.residuals == []
    assert "`ID` BIGINT UNSIGNED AUTO_INCREMENT NOT NULL" in result.full_ddl
    assert "`post_content` LONGTEXT NOT NULL" in result.full_ddl
