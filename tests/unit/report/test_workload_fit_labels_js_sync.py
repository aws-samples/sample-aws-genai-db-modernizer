"""``src/ui/src/utils/workloadFitLabels.js`` must match ``src/shared/workload_fit_labels.py``
(bug: Deliverables present a fit score as a confidence percentage).

``workloadFitLabels.js`` is a hand-kept JS copy of the Python label and definition
for the routing fit score (imported by ``ExportReport.js``'s standalone export and
the live React results page, not generated by ``scripts/sync_report_template.py``,
which only lifts ``ExportReport.js``'s own generated-script text into the ATX
renderer's templates). This test parses the JS constants and compares them against
the Python source of truth, so a wording edit left behind in only one of the two
fails CI instead of silently drifting -- the same way ``test_engine_names_js_sync.py``
pins ``engineNames.js`` and ``test_optimization_labels_js_sync.py`` pins
``optimizationLabels.js``.
"""

from __future__ import annotations

import re
from pathlib import Path

from src.shared.workload_fit_labels import (
    WORKLOAD_FIT_DEFINITION,
    WORKLOAD_FIT_LABEL,
    WORKLOAD_FIT_WORD,
)

JS_PATH = (
    Path(__file__).resolve().parents[3] / "src" / "ui" / "src" / "utils" / "workloadFitLabels.js"
)


def _extract_js_const(js_text: str, name: str) -> str:
    """Pulls a single-quoted JS string constant's value, including a continued
    ``+``-joined string literal (``workloadFitLabels.js``'s ``WORKLOAD_FIT_DEFINITION``
    is written as several concatenated string literals so no line runs long)."""
    pattern = re.compile(
        r"export const " + re.escape(name) + r"\s*=\s*((?:'(?:[^'\\]|\\.)*'\s*\+?\s*)+);",
        re.MULTILINE,
    )
    m = pattern.search(js_text)
    assert m, f"could not find JS constant {name} in workloadFitLabels.js"
    literals = re.findall(r"'((?:[^'\\]|\\.)*)'", m.group(1))
    value = "".join(literals)
    return value.replace("\\'", "'")


class TestWorkloadFitLabelsJsMatchesPython:
    def test_label_matches(self):
        js_text = JS_PATH.read_text(encoding="utf-8")
        assert _extract_js_const(js_text, "WORKLOAD_FIT_LABEL") == WORKLOAD_FIT_LABEL

    def test_word_matches(self):
        js_text = JS_PATH.read_text(encoding="utf-8")
        assert _extract_js_const(js_text, "WORKLOAD_FIT_WORD") == WORKLOAD_FIT_WORD

    def test_definition_matches(self):
        js_text = JS_PATH.read_text(encoding="utf-8")
        assert _extract_js_const(js_text, "WORKLOAD_FIT_DEFINITION") == WORKLOAD_FIT_DEFINITION

    def test_definition_says_not_a_probability(self):
        # A regression guard on the definition's content, not just its presence:
        # the whole point of the fix is that "fit" cannot be read as a success
        # probability.
        assert "not a probability" in WORKLOAD_FIT_DEFINITION
        assert "migration will succeed" in WORKLOAD_FIT_DEFINITION
