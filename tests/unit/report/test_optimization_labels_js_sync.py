"""``src/ui/src/utils/optimizationLabels.js`` must match
``OPTIMIZATION_DISPLAY_NAMES`` (#587 round 3).

``optimizationLabels.js`` is a hand-kept JS copy of the Python Aurora
optimization-category display-name map (imported by ``ExportReport.js``'s
standalone export, not generated by ``scripts/sync_report_template.py``,
which only lifts ``ExportReport.js``'s own generated-script text into the ATX
renderer's templates). This test parses the JS object literal and compares it
against the Python source of truth, so a copy left behind by a label edit
fails CI instead of silently drifting -- the same way
``test_engine_names_js_sync.py`` pins ``engineNames.js``.
"""

from __future__ import annotations

import re
from pathlib import Path

from src.shared.optimization_labels import OPTIMIZATION_DISPLAY_NAMES

JS_PATH = (
    Path(__file__).resolve().parents[3] / "src" / "ui" / "src" / "utils" / "optimizationLabels.js"
)

_ENTRY_RE = re.compile(r"""^\s*(\w+):\s*'([^']*)',?\s*$""")


def _parse_optimization_labels(js_text: str) -> dict[str, str]:
    start = js_text.index("OPTIMIZATION_LABELS = {")
    end = js_text.index("};", start)
    body = js_text[start:end]
    labels: dict[str, str] = {}
    for line in body.splitlines():
        m = _ENTRY_RE.match(line)
        if m:
            labels[m.group(1)] = m.group(2)
    return labels


class TestOptimizationLabelsJsMatchesPython:
    def test_js_labels_match_optimization_display_names(self):
        js_text = JS_PATH.read_text(encoding="utf-8")
        js_labels = _parse_optimization_labels(js_text)
        assert (
            js_labels
        ), "failed to parse any OPTIMIZATION_LABELS entries from optimizationLabels.js"
        assert js_labels == OPTIMIZATION_DISPLAY_NAMES

    def test_extraction_sees_every_contract_category(self):
        # A regression guard on the parser itself, and on contract coverage:
        # every Optimization.category the Aurora contracts allow (#587 round 3).
        js_text = JS_PATH.read_text(encoding="utf-8")
        js_labels = _parse_optimization_labels(js_text)
        for category in ("partitioning", "index", "read_replica", "io_optimized", "other"):
            assert category in js_labels, f"no display name for {category}"
        assert js_labels["read_replica"] == "Read replica"
        assert js_labels["io_optimized"] == "I/O-Optimized storage"
