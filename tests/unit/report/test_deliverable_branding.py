"""Every deliverable names one product, "Database Modernizer Assessment Tool" (#954).

The guard covers each file of the deliverables folder (#987: the executive report, the
engineering report, the assessment data JSON and the folder index), rendered from
every saved report fixture, plus the rule itself on ordinary prose.
"""

from __future__ import annotations

import io
import json
from pathlib import Path

import pytest
from pypdf import PdfReader

from src.report import deliverables as dl
from src.storage.local_store import LocalArtifactStore
from tests.branding import hits, visible_html

REPO = Path(__file__).resolve().parents[3]
FIXTURES = sorted((Path(__file__).parent / "fixtures").glob("*.json"))
PRODUCT = "Database Modernizer Assessment Tool"


def _texts(name: str, content: bytes) -> list[str]:
    if name.endswith(".pdf"):
        reader = PdfReader(io.BytesIO(content))
        meta = " ".join(str(v) for v in (reader.metadata or {}).values())
        return [meta, *[(p.extract_text() or "") for p in reader.pages]]
    return [content.decode("utf-8")]


@pytest.mark.parametrize("fixture", FIXTURES, ids=[f.stem for f in FIXTURES])
def test_every_deliverable_names_only_this_product(fixture: Path, tmp_path: Path) -> None:
    store = LocalArtifactStore(base_dir=str(tmp_path))
    key = "db/job-1/synthesis/v1/report.json"
    store.write_json(key, json.loads(fixture.read_text()))
    rendered = dl.render_deliverables(store, "job-1", "db", key)
    files = {entry.filename: item.content for entry, item in rendered.folder_files()}
    files[dl.INDEX_FILENAME] = dl.render_folder_index(
        "db", "job-1", 1, [e for e, _ in rendered.folder_files()]
    ).encode("utf-8")
    assert set(files) == set(dl.FOLDER_FILENAMES)
    found = [
        f"{name}: {h}" for name, data in files.items() for t in _texts(name, data) for h in hits(t)
    ]
    assert found == []
    assert PRODUCT in files[dl.INDEX_FILENAME].decode("utf-8")
    assert PRODUCT in " ".join(_texts("executive-report.pdf", files["executive-report.pdf"]))


@pytest.mark.parametrize(
    "text",
    [
        "The transformation of the schema takes two waves.",
        "A Lambda function transforms and routes changes.",
        "Data transformations run in the application layer.",
        "Latex and Matxx are not products.",
    ],
)
def test_ordinary_prose_passes(text: str) -> None:
    assert hits(text) == []


@pytest.mark.parametrize(
    "text",
    [
        "Generated by AWS Transform",
        "generated by aws   transform",
        "Run the transform step first.",
        "TRANSFORM the rows.",
        "Handled by ATX jobs.",
        "(atx)",
    ],
)
def test_another_product_name_fails(text: str) -> None:
    assert hits(text) != []


def test_script_and_style_bodies_are_not_text() -> None:
    html = (
        "<style>.a{transform:scale(1)}</style><p>ok</p>"
        "<script>ctx.setTransform(1,0,0,1,0,0); resetTransform()</script>"
    )
    assert hits(visible_html(html)) == []
    assert hits(visible_html('<p aria-label="AWS Transform">x</p>')) != []
