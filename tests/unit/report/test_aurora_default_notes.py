"""#156: a source DEFAULT the Aurora DDL dropped or rewrote reaches every deliverable.

The schema merge writes one deterministic ``column_default`` app-layer note per
such column into ``schema_output.json``; synthesis carries ``app_layer_notes``
into ``report.json``'s ``schema_designs``; the engineering report lists them in
the engine's section, including the identity restart step for a sequence.
"""

from __future__ import annotations

from src.agents.referee.synthesis_handler import _build_aurora_schema_summary
from src.contracts.aurora_postgresql_model_output import AuroraPostgresqlModelOutputContract
from src.contracts.schema_design_input import AgentTable
from src.report import renderers
from src.tools.schema.aurora_common.delta_merge import AuroraDesignBase, merge_design_delta
from src.tools.validation.customer_text_guard import scan_json, scan_markdown


def _table() -> AgentTable:
    return AgentTable.model_validate(
        {
            "table_id": "db.orders",
            "table_name": "orders",
            "row_count": 10,
            "primary_key": ["id"],
            "columns": [
                {
                    "column_name": "id",
                    "data_type": "bigint",
                    "normalized_data_type": "integer",
                    "nullable": False,
                    "default_value": "(NEXT VALUE FOR [dbo].[order_seq])",
                },
                {
                    "column_name": "placed_at",
                    "data_type": "datetime",
                    "normalized_data_type": "datetime",
                    "nullable": False,
                    "default_value": "((0))",
                },
                {
                    "column_name": "who",
                    "data_type": "nvarchar",
                    "normalized_data_type": "string",
                    "max_length": 50,
                    "nullable": True,
                    "default_value": "(suser_sname())",
                },
                {
                    "column_name": "status",
                    "data_type": "nvarchar",
                    "normalized_data_type": "string",
                    "max_length": 10,
                    "nullable": True,
                    "default_value": "(N'open')",
                },
            ],
        }
    )


def _schema_output() -> dict:
    base = AuroraDesignBase(
        engine="aurora_postgresql",
        job_id="j",
        source_database="db",
        source_engine="sqlserver",
        tables=[_table()],
    )
    merged = merge_design_delta(base, {"delta_version": "1.0"})
    assert merged.errors == []
    return merged.output


def test_schema_output_carries_one_note_per_changed_default():
    output = _schema_output()
    contract = AuroraPostgresqlModelOutputContract.model_validate(output)
    notes = {n.source_object: n for n in contract.app_layer_notes}
    assert set(notes) == {"orders.id", "orders.placed_at", "orders.who"}
    assert all(n.feature == "column_default" for n in notes.values())
    assert "highest migrated value" in notes["orders.id"].recommendation
    assert "RESTART WITH" in notes["orders.id"].recommendation
    assert "drops it" in notes["orders.placed_at"].recommendation
    assert "suser_sname" in notes["orders.who"].recommendation  # the source text, quoted
    assert "\"status\" VARCHAR(10) DEFAULT 'open'" in output["generated_ddl"]
    assert '"id" BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL' in output["generated_ddl"]


def test_report_json_and_engineering_report_show_the_notes():
    summary = _build_aurora_schema_summary("aurora_postgresql", _schema_output())
    assert [n["source_object"] for n in summary["app_layer_notes"]] == [
        "orders.id",
        "orders.placed_at",
        "orders.who",
    ]
    report = {"database_name": "db", "schema_designs": {"aurora_postgresql": summary}}
    assert scan_json(report) == []

    md = renderers.render_engineering_report_md(report)
    section = md.split("### Aurora PostgreSQL", 1)[1]
    assert "**Column defaults changed or dropped (3):**" in section
    assert "- `orders.id`: " in section and "highest migrated value" in section
    assert "- `orders.placed_at`: " in section
    assert "column_default" not in md
    assert scan_markdown(md) == []


def test_other_app_layer_notes_render_with_a_readable_feature():
    design = {
        "status": "completed",
        "tables": [],
        "app_layer_notes": [
            {"feature": "time_zone", "source_object": "t.a", "recommendation": "store UTC"}
        ],
    }
    md = renderers.render_engineering_report_md(
        {"database_name": "db", "schema_designs": {"aurora_mysql": design}}
    )
    assert "**Application-layer notes (1):**" in md
    assert "- Time zone on `t.a`: store UTC" in md
    assert scan_markdown(md) == []
