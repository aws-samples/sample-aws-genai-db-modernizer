/**
 * #957: the UI names one product, "Database Modernizer Assessment Tool", and
 * never shows "ATX", "AWS Transform" or "transform" (maintainer rule,
 * 2026-10-16). The UI runs locally; the hosted delivery channel's name must not
 * reach a page or a label.
 *
 * What a user can see comes from four places, and each is checked:
 * - every English string in src/locales/en.json;
 * - every string literal, template string and JSX text in the UI source
 *   (non-test files);
 * - public/index.html (the browser tab title and description) and the
 *   side-nav and header configuration.
 *
 * Comments are not shown to anyone and are not checked. A CSS `transform:`
 * declaration inside an inline style sheet is a property name, not text.
 */
const fs = require('fs');
const path = require('path');
const { parse } = require('@babel/parser');
const traverse = require('@babel/traverse').default;

import en from '../locales/en.json';

// GlobalConfigurations.js imports Cloudscape's Box (ESM, not transformed by
// Jest) for its table helpers; only its plain config objects are read here.
jest.mock('@cloudscape-design/components/box', () => () => null);
import { LayoutConfigurations, SideNavigationConfigurations } from '../config/GlobalConfigurations';

const PRODUCT = 'Database Modernizer Assessment Tool';
const UI_SRC = path.resolve(__dirname, '..');
const PUBLIC = path.resolve(__dirname, '../../public');

const FORBIDDEN = /\bATX\b|AWS\s+Transform|transform/i;

// A CSS `transform:` declaration in an inline <style> or style string.
function withoutCss(text) {
  return text.replace(/\btransform\s*:/gi, '').replace(/\btext-transform\b/gi, '');
}

function forbiddenIn(text) {
  return FORBIDDEN.test(withoutCss(text));
}

function uiSourceFiles(dir) {
  const out = [];
  for (const name of fs.readdirSync(dir)) {
    if (name === '__tests__' || name === 'node_modules') continue;
    // `dir` and `name` come from walking the repo's own src/ui/src tree.
    // nosemgrep: javascript.lang.security.audit.path-traversal.path-join-resolve-traversal.path-join-resolve-traversal -- path built from the repo's own tree, not input
    const full = path.join(dir, name);
    if (fs.statSync(full).isDirectory()) out.push(...uiSourceFiles(full));
    else if (full.endsWith('.js')) out.push(full);
  }
  return out;
}

function visibleStrings(file) {
  const ast = parse(fs.readFileSync(file, 'utf8'), { sourceType: 'module', plugins: ['jsx'] });
  const found = [];
  const add = (value, node) => found.push({ value, line: node.loc.start.line });
  traverse(ast, {
    StringLiteral(p) { add(p.node.value, p.node); },
    TemplateElement(p) { add(p.node.value.cooked || p.node.value.raw, p.node); },
    JSXText(p) { add(p.node.value, p.node); },
  });
  return found;
}

describe('the forbidden-name check itself', () => {
  test.each([
    'Generated by AWS Transform',
    'Upload to ATX',
    'Transform job',
    'transformation plan',
  ])('flags %p', (text) => {
    expect(forbiddenIn(text)).toBe(true);
  });

  test.each([
    '@keyframes f { from { transform: translateY(12px); } }',
    '.x { text-transform: uppercase; }',
    PRODUCT,
  ])('allows %p', (text) => {
    expect(forbiddenIn(text)).toBe(false);
  });
});

test('no English UI string names ATX, AWS Transform or transform', () => {
  const offending = Object.entries(en).filter(([, value]) => forbiddenIn(String(value)));
  expect(offending).toEqual([]);
});

test('no string the UI source renders names ATX, AWS Transform or transform', () => {
  const offending = [];
  for (const file of uiSourceFiles(UI_SRC)) {
    for (const { value, line } of visibleStrings(file)) {
      if (forbiddenIn(value)) offending.push(`${path.relative(UI_SRC, file)}:${line}: ${value.slice(0, 80)}`);
    }
  }
  expect(offending).toEqual([]);
});

test('public/index.html names only the product', () => {
  // Parsed, not regex-stripped: comments are not part of the document's text,
  // and the title and description are read as the browser reads them.
  const html = fs.readFileSync(path.join(PUBLIC, 'index.html'), 'utf8');
  const doc = new DOMParser().parseFromString(html, 'text/html');
  expect(forbiddenIn(doc.documentElement.textContent)).toBe(false);
  expect(doc.title).toBe(PRODUCT);
  const description = doc.querySelector('meta[name="description"]').getAttribute('content');
  expect(description).toBe(PRODUCT);
  expect(forbiddenIn(description)).toBe(false);
});

test('the header and the side navigation carry the product name', () => {
  expect(LayoutConfigurations['application-title']).toBe(PRODUCT);
  expect(SideNavigationConfigurations.header.text).toBe(PRODUCT);
});

test('every "Database Modernizer" in an English string is the full product name', () => {
  const offending = Object.entries(en).filter(([, value]) => {
    const text = String(value);
    const all = (text.match(/Database Modernizer/g) || []).length;
    const full = (text.match(/Database Modernizer Assessment Tool/g) || []).length;
    return all !== full;
  });
  expect(offending).toEqual([]);
});
