#: Prefixes of the spatial function families (``ST_Distance``, ``MBRContains``).
_BUILTIN_PREFIXES = ("ST_", "MBR")


def is_builtin_function(name: str) -> bool:
    """Whether ``name`` is a MySQL 8.0 built-in function (case-insensitive)."""
    upper = name.upper()
    return upper in _BUILTINS or upper.startswith(_BUILTIN_PREFIXES)
